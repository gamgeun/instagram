"""롱폼 대본 말투 검사. 음성을 만들기 전에 돌린다.
사용법: python3 longform/lint_script.py longform/ep01v3/script.v4.json
걸리면 번호·표현·이유를 출력하고 종료 코드 1"""
import json, re, sys

RULES = [
    # 예고형 화법: 영상이 할 일을 말한다
    (r'살펴[보봅]', '예고형 화법'), (r'알아[보봅]', '예고형 화법'), (r'따라가\s?[보봅]', '예고형 화법'),
    (r'확인합니다|확인해\s?[보봅]', '예고형 화법'), (r'열어\s?[보봅]', '예고형 화법'), (r'이야기해\s?[보봅]', '예고형 화법'),
    (r'준비했습니다|소개합니다|정리하면|정리해\s?[보봅]', '예고형 화법'),
    # 번역투 존재 구문
    (r'숨어\s?있', '번역투·비유(숨어 있다)'), (r'(문제|비결|핵심|이유|답)(은|는)\s', '번역투(~은 ~에 있었다) 의심'),
    (r'(이|라는) 숫자가 있습니다', '번역투 존재 구문'), (r'에는 .{0,12}(있습니다|있었습니다)[.]?$', '번역투 존재 구문 의심'),
    # 사용자 글쓰기 규칙
    (r'아니라', 'A가 아니라 B'), (r'문제가 생', '예고 문장 의심'), (r'가깝습니다', 'A보다 B에 가깝다'), (r'중요한 것은|분명합니다', '선언형 마무리'),
    (r'(의|이) (결|농도|밀도)\b', '추상 감성어'), (r'시대가 열', '상투 비유'), (r'막을 올', '관용 표현'),
]

S = json.load(open(sys.argv[1]))
bad = 0
for i, L in enumerate(S['lines']):
    for sent in re.split(r'(?<=[.?!])\s+', L.get('sub', '')):
        for pat, why in RULES:
            m = re.search(pat, sent)
            if m:
                bad += 1
                print(f'{i:2d}  [{why}]  "{m.group(0)}"  ← {sent}')
print('걸린 곳 없음' if not bad else f'{bad}곳')
sys.exit(1 if bad else 0)
